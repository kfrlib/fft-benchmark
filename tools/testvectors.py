from mpmath import mp, mpc, pi, exp, mpf, nstr
mp.prec = 256   # bits of precision

def dft(x):
    N = len(x)
    X = [mpc(0) for _ in range(N)]
    for k in range(N):
        for n in range(N):
            X[k] += x[n] * exp(-2j * pi * k * n / N)
        # X[k] /= mp.sqrt(N)  # Optional normalization
    return X

def print_vector(X, name, *, is_complex=True):
    print(f"extern const double {name}[];")
    print(f"const double {name}[] = {{")
    for k in range(len(X)):
        print(f"    {float(X[k].real).hex():26}, // {nstr(X[k].real, 20)}")
        if is_complex:
            print(f"    {float(X[k].imag).hex():26}, // {nstr(X[k].imag, 20)}")
    print("};\n")

print('// This file is auto-generated by testvectors.py. Do not edit manually.\n')

def rnd():
    return mp.rand() * 2 - 1

for s in [60, 61, 62, 64]:
    r = [mpc(rnd(), 0) for _ in range(s)]
    rout = dft(r)[0:s//2+1]
    print(f"// DFT test vector of size {s} -> {len(rout)} complex outputs")
    print_vector(r, f'dft_testvector_real_input{s}', is_complex=False)
    print_vector(rout, f'dft_testvector_real_output{s}')
    
    r = [mpc(rnd(), rnd()) for _ in range(s)]
    rout = dft(r)
    print_vector(r, f'dft_testvector_complex_input{s}')
    print_vector(rout, f'dft_testvector_complex_output{s}')
